"""Pack assets/ui/*.png into pre-decoded LVGL image descriptors for the firmware.

The simulator decodes PNG at runtime (lodepng + 8MB LV_MEM); a 360x360 ARGB frame
would cost ~518KB of RAM on the device, so the firmware gets flat pixel arrays
instead: background -> RGB565, sprites -> ARGB8888 (LVGL's byte order is B,G,R,A).

Writes firmware/main/tf_assets_gen.c, which implements tf_asset_src() from
shared/ui/tf_assets.h.

    python tools/gen_fw_assets.py
"""
import os

import numpy as np
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SRC = os.path.join(ROOT, "assets", "ui")
OUT = os.path.join(ROOT, "firmware", "main", "tf_assets_gen.c")

ALPHA = "LV_COLOR_FORMAT_ARGB8888"
RGB565 = "LV_COLOR_FORMAT_RGB565"

# (shared/ui/tf_assets.h enum member, png, colour format)
ASSETS = [
    ("BG",         "garden_bg.png",   RGB565),
    ("FROG_HOME",  "frog_home.png",   ALPHA),
    ("FROG_ANGRY", "frog_angry.png",  ALPHA),
    ("CLOVER",     "clover.png",      ALPHA),
    ("ICON_SHOP",  "icon_shop.png",   ALPHA),
    ("ICON_GO",    "icon_go.png",     ALPHA),
    ("ICON_CARD",  "icon_card.png",   ALPHA),
    ("ICON_SPD",   "icon_spd.png",    ALPHA),
]

# tf_ui paints this sky colour behind the background, and the round mask leaves the
# corners black - invisible on the round panel, but RGB565 has no alpha to fall back
# on, so the sprite corner handling below still flattens transparent pixels onto it.
SKY = (0xBF, 0xE3, 0xFF)


def load(file):
    im = Image.open(os.path.join(SRC, file)).convert("RGBA")
    a = np.asarray(im).astype(np.int16)
    rgb, alpha = a[..., :3], a[..., 3:4]
    return np.where(alpha > 0, rgb, np.full_like(rgb, SKY)), alpha[..., 0]


def to_rgb565_bytes(rgb):
    """lv_color16_t is blue:5, green:6, red:5 -> blue occupies the low bits."""
    r = (rgb[..., 0] >> 3).astype(np.uint16)
    g = (rgb[..., 1] >> 2).astype(np.uint16)
    b = (rgb[..., 2] >> 3).astype(np.uint16)
    return (b | (g << 5) | (r << 11)).astype("<u2").reshape(-1).view(np.uint8)


def to_argb8888_bytes(rgb, alpha):
    """lv_color32_t is {blue, green, red, alpha}, so ARGB8888 is B,G,R,A in memory."""
    return np.dstack([rgb[..., 2], rgb[..., 1], rgb[..., 0], alpha]).astype(np.uint8).reshape(-1)


def carray(name, data, per_line=24):
    rows = [",".join(f"0x{b:02x}" for b in data[i:i + per_line])
            for i in range(0, len(data), per_line)]
    return (f"static const uint8_t {name}[] __attribute__((aligned(16))) = {{\n"
            + "".join(f"    {r},\n" for r in rows) + "};\n")


def main():
    chunks, table, total = [], [], 0
    for enum, file, cf in ASSETS:
        rgb, alpha = load(file)
        h, w = rgb.shape[:2]
        px = to_rgb565_bytes(rgb) if cf == RGB565 else to_argb8888_bytes(rgb, alpha)
        sym, data = f"tf_dsc_{enum.lower()}", f"tf_px_{enum.lower()}"
        chunks.append(f"/* {file}: {w}x{h}, {cf}, {len(px)} bytes */")
        chunks.append(carray(data, px))
        chunks.append(
            f"static const lv_image_dsc_t {sym} = {{\n"
            "    .header = {\n"
            "        .magic = LV_IMAGE_HEADER_MAGIC,\n"
            f"        .cf = {cf},\n"
            f"        .w = {w},\n"
            f"        .h = {h},\n"
            f"        .stride = {w * (2 if cf == RGB565 else 4)},\n"
            "    },\n"
            f"    .data_size = sizeof({data}),\n"
            f"    .data = {data},\n"
            "};\n"
        )
        table.append(f"    [TF_ASSET_{enum}] = &{sym},")
        total += len(px)

    body = (
        "/* Generated by tools/gen_fw_assets.py - do not edit.\n"
        f"   {len(ASSETS)} assets, {total} bytes of pixel data. */\n"
        '#include "tf_assets.h"\n#include "lvgl.h"\n\n'
        + "\n".join(chunks)
        + "\nstatic const void *const s_src[TF_ASSET_NUM] = {\n"
        + "\n".join(table) + "\n};\n\n"
        "const void * tf_asset_src(int which)\n"
        "{\n"
        "    return (which >= 0 && which < TF_ASSET_NUM) ? s_src[which] : NULL;\n"
        "}\n"
    )
    with open(OUT, "w", newline="\n") as f:
        f.write(body)
    print(f"wrote {os.path.relpath(OUT, ROOT)}  ({total // 1024} KB pixel data, "
          f"{os.path.getsize(OUT) // 1024} KB source)")


if __name__ == "__main__":
    main()
