"""Generate the LVGL subset fonts from the UI string literals.

Only the glyphs the game actually draws get compiled in (~150 hanzi => ~40KB),
which also guarantees no missing-glyph holes on device: add a new Chinese string,
re-run this, and it appears in the font.

    python tools/gen_font.py

Needs: npm install lv_font_conv (already vendored under tools/node_modules).
"""
import os
import re
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
TOOLS = os.path.join(ROOT, "tools")
OUT_DIR = os.path.join(ROOT, "shared", "ui")
CONV = os.path.join(TOOLS, "node_modules", "lv_font_conv", "lv_font_conv.js")

FONTS = [
    ("tf_font_cn_16", r"C:\Windows\Fonts\Noto Sans SC (TrueType).otf", 16),
    ("tf_font_cn_20", r"C:\Windows\Fonts\Noto Sans SC Bold (TrueType).otf", 20),
]

SOURCES = ["shared/ui/tf_ui.c", "shared/core/tf_core.c"]
LITERAL_RE = re.compile(r'"((?:[^"\\\n]|\\.)*)"', re.S)


def used_chars():
    cps = set(range(0x20, 0x7F))          # printable ASCII
    for rel in SOURCES:
        src = open(os.path.join(ROOT, rel), encoding="utf-8").read()
        for lit in LITERAL_RE.findall(src):
            for ch in lit:
                if ord(ch) > 0x7F:
                    cps.add(ord(ch))
    return cps


def to_ranges(cps):
    cps = sorted(cps)
    out, start, prev = [], cps[0], cps[0]
    for c in cps[1:]:
        if c == prev + 1:
            prev = c
            continue
        out.append((start, prev))
        start = prev = c
    out.append((start, prev))
    return ",".join(f"0x{a:X}" if a == b else f"0x{a:X}-0x{b:X}" for a, b in out)


def main():
    if not os.path.exists(CONV):
        sys.exit("lv_font_conv missing: run npm install lv_font_conv in tools/")

    # Codepoints are passed numerically: Chinese on argv would hit the ANSI codepage.
    ranges = to_ranges(used_chars())
    print(f"{len(ranges.split(','))} ranges, {ranges[:60]}...")

    for name, path, size in FONTS:
        dst = os.path.join(OUT_DIR, name + ".c")
        cmd = ["node", CONV,
               "--font", path, "--size", str(size), "--bpp", "4",
               "--format", "lvgl", "--lv-font-name", name,
               "--range", ranges, "--output", dst]
        r = subprocess.run(cmd, cwd=TOOLS, capture_output=True, text=True)
        if r.returncode:
            sys.exit(f"{name} failed:\n{r.stdout}\n{r.stderr}")
        print(f"{name}: {os.path.getsize(dst) // 1024} KB")

    header = (
        "/* Generated by tools/gen_font.py - do not edit. */\n"
        "#ifndef TF_FONTS_H\n#define TF_FONTS_H\n\n"
        '#include "lvgl.h"\n\n'
        + "".join(f"extern const lv_font_t {n};\n" for n, _, _ in FONTS)
        + "\n#define TF_FONT_BODY   (&" + FONTS[0][0] + ")\n"
        + "#define TF_FONT_TITLE  (&" + FONTS[1][0] + ")\n\n"
        "#endif\n")
    with open(os.path.join(OUT_DIR, "tf_fonts.h"), "w", encoding="utf-8") as f:
        f.write(header)
    print("wrote shared/ui/tf_fonts.h")


if __name__ == "__main__":
    main()
